#requires -Version 5.1
#requires -RunAsAdministrator
<#
.SYNOPSIS
Bracket three documented timestamp queries with same-run topology and ETW health.
.DESCRIPTION
Requires the pinned build manifest generated by Build-NdisExperiment.ps1 and
Python 3.11+. No private commands, configuration changes or packet transmission.
Creates one temporary Request/marker ETW session, capped at 8 MiB. Every child
has a timeout; uncertain starts still enter cleanup. Raw output is PRIVATE.
Exit 0 acquisition/cleanup complete, not semantic qualification; 1 failure.
External interruption recovery: logman stop <session.json SessionName> -ets.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][ValidateRange(1,2147483647)][int]$InterfaceIndex,
    [Parameter(Mandatory=$true)][Guid]$ExpectedInterfaceGuid,
    [Parameter(Mandatory=$true)][string]$BuildDirectory,
    [Parameter(Mandatory=$true)][ValidatePattern('^[0-9a-fA-F]{64}$')][string]$ExpectedManifestSha256,
    [Parameter(Mandatory=$true)][string]$PythonPath,
    [Parameter(Mandatory=$true)][string]$OutputDirectory
)
$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
$repo=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$session='WifiNdisStatus-'+[Guid]::NewGuid().ToString('N')
$output=[IO.Path]::GetFullPath($OutputDirectory)
if(Test-Path -LiteralPath $output){throw 'Output directory must not already exist.'}
$null=New-Item -ItemType Directory -Path $output
$attempted=$false;$cleanup=$false;$exitCode=1;$failure=$null
$logman=Join-Path $env:SystemRoot 'System32/logman.exe'
$build=[IO.Path]::GetFullPath($BuildDirectory)
$healthTool=$null

function Invoke-BoundedChild {
    param([string]$File,[string[]]$Arguments,[string]$Label,[int]$TimeoutMs=10000)
    if(@($Arguments | Where-Object {$_ -match '["\r\n]'}).Count){throw 'Unsupported argument character.'}
    $quoted=@($Arguments | ForEach-Object {'"'+$_+'"'}) -join ' '
    $child=Start-Process -FilePath $File -ArgumentList $quoted -WindowStyle Hidden -PassThru `
        -RedirectStandardOutput (Join-Path $output ($Label+'.stdout.txt')) `
        -RedirectStandardError (Join-Path $output ($Label+'.stderr.txt'))
    try {
        $null=$child.Handle # Cache the handle before exit for Windows PowerShell 5.1.
        if(-not $child.WaitForExit($TimeoutMs)){
            try {$child.Kill()} catch {if(-not $child.HasExited){throw}}
            if(-not $child.WaitForExit(2000)){throw ('Child termination unconfirmed: '+$Label)}
            throw ('Child timeout: '+$Label)
        }
        $child.Refresh()
        if($child.ExitCode -ne 0){throw ('Child failed: '+$Label+' exit '+$child.ExitCode)}
        [pscustomobject]@{ProcessId=$child.Id;ExitCode=$child.ExitCode} | ConvertTo-Json |
            Set-Content -LiteralPath (Join-Path $output ($Label+'.process.json')) -Encoding UTF8
    } finally {$child.Dispose()}
}

function Get-ExactAdapter {
    $items=@(Get-NetAdapter -IncludeHidden | Where-Object {$_.ifIndex -eq $InterfaceIndex})
    if($items.Count -ne 1){throw 'Adapter index is not unique.'}
    $item=$items[0]
    if([Guid]$item.InterfaceGuid -ne $ExpectedInterfaceGuid -or $item.Status -ne 'Up' -or
       $item.DriverVersion -ne '1.0.4374.1300' -or $item.InterfaceDescription -notlike '*Qualcomm*7800*'){
        throw 'Adapter identity/state/build differs from approved target.'
    }
    if(-not $item.DriverName.StartsWith('\SystemRoot\',[StringComparison]::OrdinalIgnoreCase)){
        throw 'Unexpected installed driver path form.'
    }
    $driverPath=Join-Path $env:SystemRoot $item.DriverName.Substring(12)
    if((Get-FileHash -LiteralPath $driverPath).Hash -ne 'CA884CE1A22113194F3C467F36ABC39AFB0C137E5A7A8E2697420438B21E4115'){
        throw 'Installed driver hash mismatch.'
    }
    return $item
}


try {
    . (Join-Path $PSScriptRoot 'NdisV2Health.ps1')
    $before=Get-ExactAdapter
    $manifestPath=Join-Path $build 'manifest.json'
    if((Get-FileHash -LiteralPath $manifestPath).Hash -ne $ExpectedManifestSha256){throw 'Build manifest hash mismatch.'}
    $manifest=Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    if($manifest.schema -ne 'ndis-experiment-build/v1' -or $manifest.architecture -ne 'arm64'){
        throw 'Live Qualcomm experiment requires the ARM64 build manifest.'
    }
    $expectedSources=@('experiments/qualcomm/ndis_query_probe.c','experiments/qualcomm/ndis_trace_health.c','experiments/qualcomm/Build-NdisExperiment.ps1')
    if(@($manifest.sources).Count -ne 3 -or @($manifest.binaries).Count -ne 2){throw 'Unexpected build manifest entries.'}
    $seen=@{}
    foreach($source in $manifest.sources){
        if($source.path -notin $expectedSources -or $seen.ContainsKey($source.path)){throw 'Unexpected or duplicate source.'}
        $seen[$source.path]=$true
        if((Get-FileHash -LiteralPath (Join-Path $repo $source.path)).Hash -ne $source.sha256){throw 'Built source changed.'}
    }
    $seen=@{}
    foreach($binary in $manifest.binaries){
        if($binary.name -notin @('ndis_query_probe.exe','ndis_trace_health.exe') -or $seen.ContainsKey($binary.name)){throw 'Unexpected or duplicate binary.'}
        $seen[$binary.name]=$true
        if((Get-FileHash -LiteralPath (Join-Path $build $binary.name)).Hash -ne $binary.sha256){throw 'Built executable changed.'}
    }
    $probe=Join-Path $build 'ndis_query_probe.exe'
    $healthTool=Join-Path $build 'ndis_trace_health.exe'
    $snapshot=Join-Path $PSScriptRoot 'ndis_evidence.py'
    $exporter=Join-Path $PSScriptRoot 'Export-NdisNamedEvents.ps1'
    [pscustomobject]@{SessionName=$session;InterfaceIndex=$InterfaceIndex;InterfaceGuid=$ExpectedInterfaceGuid;
        DriverVersion=$before.DriverVersion;BuildManifestSha256=$ExpectedManifestSha256;
        CaptureScriptSha256=(Get-FileHash -LiteralPath $PSCommandPath).Hash;
        SnapshotScriptSha256=(Get-FileHash -LiteralPath $snapshot).Hash;
        ExportScriptSha256=(Get-FileHash -LiteralPath $exporter).Hash;
        HealthScriptSha256=(Get-FileHash -LiteralPath (Join-Path $PSScriptRoot 'NdisV2Health.ps1')).Hash;
        NdisSha256=(Get-FileHash -LiteralPath (Join-Path $env:SystemRoot 'System32/drivers/ndis.sys')).Hash} |
        ConvertTo-Json | Set-Content -LiteralPath (Join-Path $output 'session.json') -Encoding UTF8
    Invoke-BoundedChild -File $PythonPath -Arguments @($snapshot,'snapshot','--if-index',[string]$InterfaceIndex,'--expected-guid',$ExpectedInterfaceGuid.ToString('D'),'--output',(Join-Path $output 'topology-before.json')) -Label 'snapshot-before'
    $providerFile=Join-Path $output 'providers.txt'
    @('"{cdead503-17f5-4a3e-b7ae-df8cc2902eb9}" 0x1 5','"{209754d0-15cd-42dd-a9b9-d1b38a606c08}" 0x1 4') |
        Set-Content -LiteralPath $providerFile -Encoding ASCII
    $etl=Join-Path $output 'ndis.etl'
    $attempted=$true
    Invoke-BoundedChild -File $logman -Arguments @('start',$session,'-pf',$providerFile,'-ct','perf','-o',$etl,'-f','bin','-max','8','-ets') -Label 'trace-start'
    foreach($operation in @('supported','active','cross')){
        Invoke-BoundedChild -File $probe -Arguments @([string]$InterfaceIndex,$operation,'--markers') -Label ('query-'+$operation)
    }
    Invoke-BoundedChild -File $PythonPath -Arguments @($snapshot,'snapshot','--if-index',[string]$InterfaceIndex,'--expected-guid',$ExpectedInterfaceGuid.ToString('D'),'--output',(Join-Path $output 'topology-after.json')) -Label 'snapshot-after'
    Invoke-BoundedChild -File $healthTool -Arguments @('query',$session) -Label 'controller-query'
    $exitCode=0
} catch {$failure=$_.Exception.Message}
finally {
    if($attempted){
        try {Invoke-BoundedChild -File $healthTool -Arguments @('stop',$session) -Label 'controller-stop';$cleanup=$true}
        catch {
            $exitCode=1;$failure='Native trace stop failed; controller health is unqualified.'
            try {Invoke-BoundedChild -File $logman -Arguments @('stop',$session,'-ets') -Label 'trace-recovery-stop';$cleanup=$true}
            catch {$failure='Trace cleanup unconfirmed; stop exact SessionName in session.json.'}
        }
    }
}
if($exitCode -eq 0){
    try {
        Invoke-BoundedChild -File $healthTool -Arguments @('header',$etl) -Label 'trace-health'
        $native=@(Get-Content -LiteralPath (Join-Path $output 'trace-health.stdout.txt') | ForEach-Object {$_ | ConvertFrom-Json})
        $header=$native[0];$summary=$native[-1]
        $stopped=Get-Content -LiteralPath (Join-Path $output 'controller-stop.stdout.txt') -Raw | ConvertFrom-Json
        Assert-NdisV2Health -Header $header -Summary $summary -Stopped $stopped -EtlBytes (Get-Item -LiteralPath $etl).Length
        $ps=Join-Path $env:SystemRoot 'System32/WindowsPowerShell/v1.0/powershell.exe'
        Invoke-BoundedChild -File $ps -Arguments @('-NoProfile','-File',$exporter,'-EtlPath',$etl,'-OutputPath',(Join-Path $output 'named-events.json')) -Label 'named-export'
        $null=Get-ExactAdapter
    } catch {$exitCode=1;$failure=$_.Exception.Message}
}
[pscustomobject]@{AcquisitionCompleted=($exitCode -eq 0);TraceCleanupSucceeded=$cleanup;
    Error=$failure;PrivateRequestSent=$false;QueriesPlanned=3;Qualification='Requires strict offline correlation'} |
    ConvertTo-Json | Set-Content -LiteralPath (Join-Path $output 'result.json') -Encoding UTF8
exit $exitCode
